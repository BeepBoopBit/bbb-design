import { expect, test } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

for (const mode of ['light', 'dark']) test(`document pattern supports library navigation, account access, and mobile focus in ${mode}`, async ({ page }) => {
  await page.goto('/')
  await page.evaluate(mode => localStorage.setItem('bbb-gallery-appearance', JSON.stringify({ brand: 'bbb', mode, density: 'comfortable' })), mode)
  await page.reload()
  await page.getByRole('searchbox', { name: 'Search gallery' }).fill('Workspace shell')
  const variants = page.getByRole('radiogroup', { name: 'Workspace layout' })
  await variants.getByRole('radio', { name: 'Branded', exact: true }).focus()
  await page.keyboard.press('ArrowRight')
  const workspace = page.getByRole('group', { name: 'Document workspace example', exact: true })
  await workspace.getByRole('button', { name: 'Decisions worth remembering', exact: true }).click()
  await expect(workspace.getByRole('region', { name: 'Open document' })).toBeFocused()
  await expect(workspace.getByRole('heading', { name: 'Decisions worth remembering' })).toBeVisible()
  const search = workspace.getByRole('searchbox', { name: 'Search documents' })
  await search.fill('not a document')
  await workspace.getByRole('button', { name: 'Show all documents' }).click()
  await expect(search).toBeFocused()
  await workspace.getByRole('button', { name: 'Studio, account and workspaces' }).click()
  await page.getByRole('button', { name: 'Personal', exact: true }).click()
  await expect(workspace.getByRole('heading', { name: 'Room for discovery' })).toBeVisible()
  await workspace.getByRole('button', { name: 'Personal, account and workspaces' }).click()
  await page.getByRole('button', { name: 'Studio', exact: true }).click()
  await page.evaluate(() => { document.documentElement.style.fontSize = '200%' })
  for (const width of [320, 390]) {
    await page.setViewportSize({ width, height: 1000 })
    expect(await workspace.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
    const trigger = workspace.getByRole('button', { name: 'Open document library' })
    await trigger.click()
    const sheet = page.getByRole('dialog', { name: 'Document library', exact: true })
    await sheet.getByRole('button', { name: /Decisions worth remembering/ }).focus()
    await page.keyboard.press('Enter')
    await expect(workspace.getByRole('region', { name: 'Open document' })).toBeFocused()
    await expect(sheet).not.toBeVisible()
    expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations).toEqual([])
    await trigger.click()
    await page.keyboard.press('Escape')
    await expect(trigger).toBeFocused()
  }
})

test('standalone document workspace carries Arabic direction into mobile navigation', async ({ page }) => {
  await page.goto('/tests/fixtures/document-workspace.html')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: 'فتح المكتبة' }).click()
  const sheet = page.getByRole('dialog', { name: 'المكتبة', exact: true })
  await expect(page.locator('.bbb-modal-overlay')).toHaveAttribute('dir', 'rtl')
  await expect(page.locator('.bbb-modal-overlay')).toHaveAttribute('lang', 'ar')
  await sheet.getByRole('link', { name: 'المقدمة' }).click()
  await expect(page.getByRole('region', { name: 'المستند' })).toBeFocused()
  await expect(page.getByRole('heading', { name: 'المقدمة' })).toBeVisible()
  expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations).toEqual([])
})
