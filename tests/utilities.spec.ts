test('split pane resizes with keys and pointer, then stacks on narrow screens', async ({ page }) => {
  await example(page, 'split-pane')
  const separator = page.getByRole('separator', { name: 'Resize document library' })
  await separator.focus()
  await page.keyboard.press('ArrowRight')
  await expect(separator).toHaveAttribute('aria-valuenow', '45')
  await page.keyboard.press('End')
  await expect(separator).toHaveAttribute('aria-valuenow', '80')
  await page.keyboard.press('Home')
  await expect(separator).toHaveAttribute('aria-valuenow', '20')
  const box = (await separator.boundingBox())!
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.down()
  await page.mouse.move(box.x + 100, box.y + box.height / 2)
  await page.mouse.up()
  expect(Number(await separator.getAttribute('aria-valuenow'))).toBeGreaterThan(20)
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(separator).not.toBeVisible()
  await expect(page.getByRole('heading', { name: 'Brand direction', exact: true })).toBeVisible()
})

