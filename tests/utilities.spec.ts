test('media artwork follows live theme changes in its card and enlarged view', async ({ page }) => {
  await page.emulateMedia({ colorScheme: 'light' })
  const card = await example(page, 'media-preview')
  const artwork = card.getByRole('img', { name: 'BBB shapes in ember and teal' })
  await expect(artwork).toBeVisible()
  const lightSource = await artwork.getAttribute('src')
  await page.locator('.gallery-appearance-controls').getByRole('button', { name: /Color mode:/ }).click()
  await expect(artwork).not.toHaveAttribute('src', lightSource!)
  const darkSource = await artwork.getAttribute('src')
  const background = await card.evaluate(element => getComputedStyle(element).getPropertyValue('--bbb-color-canvas').trim())
  expect(decodeURIComponent(darkSource!)).toContain(`fill="${background}"`)
  await card.getByRole('button', { name: 'Enlarge image' }).click()
  await expect(page.getByRole('dialog').getByRole('img')).toHaveAttribute('src', darkSource!)
  await page.keyboard.press('Escape')
  await page.locator('.gallery-appearance-controls').getByRole('button', { name: /Color mode:/ }).click()
  await expect(artwork).toHaveAttribute('src', lightSource!)
})
