import { expect, test, type Page } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import { galleryCounts } from './galleryCounts'

async function example(page: Page, id: string) {
  await page.goto(`/gallery?item=${id}`)
  await expect(page.getByRole('article')).toHaveCount(1)
  return page.getByRole('article')
}

test('theme switcher toggles directly with keyboard and pointer, persists, and resolves system mode', async ({ page }) => {
  await page.emulateMedia({ colorScheme: 'dark' })
  await example(page, 'theme-switcher')
  const boundary = page.locator('#root > [data-bbb-theme]')
  const controls = page.locator('.gallery-appearance-controls')
  await expect(boundary).toHaveAttribute('data-bbb-mode', 'dark')
  await controls.getByRole('button', { name: 'Color mode: System' }).focus()
  await page.keyboard.press('Enter')
  await expect(boundary).toHaveAttribute('data-bbb-mode', 'light')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(controls.getByRole('button', { name: 'Color mode: Light' })).toBeFocused()
  await page.keyboard.press('Space')
  await expect(boundary).toHaveAttribute('data-bbb-mode', 'dark')
  await expect(controls.getByRole('button', { name: 'Color mode: Dark' })).toBeFocused()
  await page.reload()
  await page.emulateMedia({ colorScheme: 'light' })
  await expect(boundary).toHaveAttribute('data-bbb-mode', 'dark')
  await controls.getByRole('button', { name: 'Color mode: Dark' }).click()
  await expect(boundary).toHaveAttribute('data-bbb-mode', 'light')
  await controls.getByRole('button', { name: 'Appearance', exact: true }).click()
  await page.getByRole('dialog', { name: 'Gallery appearance' }).getByRole('button', { name: /Color mode/ }).click()
  await page.getByRole('option', { name: 'System', exact: true }).click()
  await page.getByRole('dialog', { name: 'Gallery appearance' }).getByRole('button', { name: 'Close popover' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.emulateMedia({ colorScheme: 'dark' })
  await expect(boundary).toHaveAttribute('data-bbb-mode', 'dark')
  await page.emulateMedia({ colorScheme: 'light' })
  await expect(boundary).toHaveAttribute('data-bbb-mode', 'light')
  await controls.getByRole('button', { name: 'Color mode: System' }).click()
  await expect(boundary).toHaveAttribute('data-bbb-mode', 'dark')
})

for (const mode of ['light', 'dark'] as const) test(`theme switcher example uses one icon action and preserves focus in ${mode}`, async ({ page }) => {
  await page.addInitScript(mode => localStorage.setItem('bbb-gallery-appearance', JSON.stringify({ mode, brand: 'bbb', density: 'comfortable' })), mode)
  const card = await example(page, 'theme-switcher')
  const boundary = card.locator('.utility-preview[data-bbb-theme]')
  const label = mode === 'light' ? 'Light' : 'Dark'
  const opposite = mode === 'light' ? 'Dark' : 'Light'
  const oppositeMode = mode === 'light' ? 'dark' : 'light'
  await expect(card.getByRole('radiogroup')).toHaveCount(0)
  await expect(card.getByRole('button', { name: /Unavailable color mode:/ })).toBeDisabled()
  const trigger = card.getByRole('button', { name: `Color mode: ${label}`, exact: true })
  await expect(trigger.locator('svg')).toHaveCount(1)
  await trigger.focus()
  await page.keyboard.press('Enter')
  await expect(boundary).toHaveAttribute('data-bbb-mode', oppositeMode)
  await expect(card.getByRole('button', { name: `Color mode: ${opposite}`, exact: true })).toBeFocused()
  await page.keyboard.press('Space')
  await expect(boundary).toHaveAttribute('data-bbb-mode', mode)
  await expect(trigger).toBeFocused()
  await trigger.click()
  await expect(boundary).toHaveAttribute('data-bbb-mode', oppositeMode)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.locator('#root > [data-bbb-theme]')).toHaveAttribute('data-bbb-mode', mode)
})

test('Gallery restores URLs and history, isolates examples, loads source, and resets local state', async ({ page }) => {
  await page.emulateMedia({ colorScheme: 'light' })
  await page.goto('/gallery')
  const navigation = page.getByRole('navigation', { name: 'Main navigation', exact: true })
  await navigation.getByRole('link', { name: `Components ${galleryCounts.components}` }).click()
  await expect(page).toHaveURL(/category=components/)
  await page.reload()
  await expect(page.getByRole('article')).toHaveCount(galleryCounts.components)
  await navigation.getByRole('link', { name: `Patterns ${galleryCounts.patterns}` }).click()
  await expect(page).toHaveURL(/category=patterns/)
  await expect(page.getByRole('article')).toHaveCount(galleryCounts.patterns)
  await expect(page.getByRole('main')).toBeFocused()
  await page.goBack()
  await expect(page).toHaveURL(/category=components/)
  await expect(page.getByRole('article')).toHaveCount(galleryCounts.components)
  await expect(page.getByRole('main')).toBeFocused()
  await page.getByRole('searchbox', { name: 'Search gallery' }).fill('theme switcher')
  await expect(page.getByRole('article')).toHaveCount(1)
  await page.reload()
  await expect(page.getByRole('searchbox', { name: 'Search gallery' })).toHaveValue('theme switcher')
  await page.getByRole('link', { name: 'Open example', exact: true }).click()
  await expect(page).toHaveURL(/item=theme-switcher/)
  const card = page.getByRole('article')
  await card.getByRole('button', { name: 'Color mode: Light', exact: true }).click()
  await expect(card.getByRole('button', { name: 'Color mode: Dark', exact: true })).toBeFocused()
  await card.getByRole('button', { name: 'Reset example' }).click()
  await expect(card.getByRole('button', { name: 'Color mode: Light', exact: true })).toBeVisible()
  await expect(card.getByRole('button', { name: 'Reset example' })).toBeFocused()
  await card.getByRole('button', { name: 'View code' }).click()
  await expect(card.getByRole('region', { name: 'Example source' })).toContainText('ThemeSwitcher')
  await page.getByRole('button', { name: 'Back to full Gallery' }).click()
  await expect(page.getByRole('article')).toHaveCount(galleryCounts.all)
})

test('copy feedback handles clipboard success and failure without losing the action', async ({ page }) => {
  await page.addInitScript(() => {
    Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async (text: string) => { (window as unknown as { copiedText: string }).copiedText = text } } })
  })
  const card = await example(page, 'copy-button')
  await card.getByRole('button', { name: 'Copy', exact: true }).filter({ hasNot: page.locator('[disabled]') }).first().click()
  await expect(card.getByRole('button', { name: 'Copied', exact: true })).toBeVisible()
  expect(await page.evaluate(() => (window as unknown as { copiedText: string }).copiedText)).toBe('Good ideas start here.')
  await page.evaluate(() => { navigator.clipboard.writeText = () => new Promise<void>(resolve => { (window as unknown as { finishCopy: () => void }).finishCopy = resolve }) })
  await card.getByRole('button', { name: 'Copied', exact: true }).click()
  const pending = card.getByRole('button', { name: 'Copy', exact: true }).first()
  await expect(pending).toHaveAttribute('aria-busy', 'true')
  await expect(pending).toBeFocused()
  await page.evaluate(() => (window as unknown as { finishCopy: () => void }).finishCopy())
  await expect(card.getByRole('button', { name: 'Copied', exact: true })).toBeFocused()
  await page.evaluate(() => { navigator.clipboard.writeText = async () => { throw new Error('Unavailable') } })
  await card.getByRole('button', { name: 'Copy invitation', exact: true }).click()
  await expect(card.getByRole('button', { name: 'Copy failed. Try again.', exact: true })).toBeVisible()
})

