import { expect, test, type Page } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

async function example(page: Page, id: string) {
  await page.goto(`/gallery?item=${id}`)
  await expect(page.getByRole('article')).toHaveCount(1)
  return page.getByRole('article')
}

test('compact search filters, clears by keyboard and pointer, and retains geometry and focus', async ({ page }) => {
  const card = await example(page, 'search-field')
  const input = card.getByRole('searchbox', { name: 'Find a document' })
  const surface = input.locator('..').locator('..')
  const before = await surface.boundingBox()
  await input.fill('design')
  await expect(card.getByRole('status')).toHaveText('1 document found.')
  await expect(card.getByRole('listitem')).toHaveCount(1)
  expect((await surface.boundingBox())?.height).toBe(before?.height)
  await input.press('Tab')
  await expect(card.getByRole('button', { name: 'Clear search' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(input).toHaveValue('')
  await expect(input).toBeFocused()
  await expect(card.getByRole('listitem')).toHaveCount(3)
  await input.fill('weekly')
  await card.getByRole('button', { name: 'Clear search' }).click()
  await expect(input).toBeFocused()
  await input.fill('no matching document')
  await expect(card.getByRole('status')).toHaveText('No documents found. Try another search.')
  await input.press('Escape')
  await expect(input).toHaveValue('')
  await expect(card.getByRole('searchbox', { name: 'Unavailable search' })).toBeDisabled()
  await page.setViewportSize({ width: 320, height: 1000 })
  await page.evaluate(() => { document.documentElement.style.fontSize = '200%' })
  await input.fill('review')
  const fontSize = await input.evaluate(element => parseFloat(getComputedStyle(element).fontSize))
  expect((await input.boundingBox())!.width).toBeGreaterThanOrEqual(fontSize * 2)
  await input.press('Tab')
  await expect(card.getByRole('button', { name: 'Clear search' })).toBeFocused()
})

test('search supports native reset, submission, consumer refs, read-only values, and dialog Escape', async ({ page }) => {
  await page.goto('/tests/fixtures/fields.html')
  const input = page.getByRole('searchbox', { name: 'Uncontrolled search' })
  await input.fill('Planning')
  await input.press('Enter')
  await expect(page.getByRole('status')).toHaveText('Planning')
  await page.getByRole('button', { name: 'Reset search' }).click()
  await expect(input).toHaveValue('Design')
  await page.getByRole('button', { name: 'Focus search' }).click()
  await expect(input).toBeFocused()
  await expect(page.getByRole('searchbox', { name: 'Read-only search' })).toHaveAttribute('readonly', '')
  await page.getByRole('searchbox', { name: 'Read-only search' }).press('Escape')
  await expect(page.getByRole('searchbox', { name: 'Read-only search' })).toHaveValue('Managed search')
  await page.getByRole('button', { name: 'Open search dialog' }).click()
  const search = page.getByRole('dialog').getByRole('searchbox', { name: 'Dialog search' })
  await expect(search).toBeFocused()
  await search.press('Escape')
  await expect(search).toHaveValue('')
  await expect(page.getByRole('dialog')).toBeVisible()
  await search.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Open search dialog' })).toBeFocused()
})

for (const variant of ['outlined', 'subtle', 'plain'] as const) {
  test(`${variant} fields retain dropdown keyboard selection, disabled options, validation, and hit areas`, async ({ page }) => {
    let card = await example(page, 'select')
    await card.getByRole('radiogroup', { name: 'Field style' }).getByText(variant, { exact: false }).click()
    const trigger = card.getByRole('button', { name: /Priority/ })
    await trigger.focus()
    await trigger.press('ArrowDown')
    await page.keyboard.press('End')
    await page.keyboard.press('Enter')
    await expect(trigger).toContainText('High')
    await expect(trigger).toBeFocused()
    expect(await card.getByRole('form').evaluate(form => new FormData(form as HTMLFormElement).get('priority'))).toBe('high')
    await expect(card.getByRole('button', { name: /Access level/ })).toBeDisabled()
    const surface = card.locator('.bbb-select .bbb-field__surface').first()
    await surface.click({ position: { x: 3, y: 3 } })
    await expect(page.getByRole('listbox')).toBeVisible()
    const options = await page.getByRole('listbox').boundingBox()
    const boundary = await surface.boundingBox()
    expect(options!.y).toBeGreaterThanOrEqual(boundary!.y + boundary!.height)
    await page.keyboard.press('Escape')
    await expect(trigger).toBeFocused()

    card = await example(page, 'combobox')
    await card.getByRole('radiogroup', { name: 'Field style' }).getByText(variant, { exact: false }).click()
    const combo = card.getByRole('combobox', { name: 'Assign to' })
    await combo.fill('Jamie')
    await combo.press('ArrowDown')
    await combo.press('Enter')
    await expect(combo).toHaveValue('Jamie Chen')
    await expect(combo).toBeFocused()

    card = await example(page, 'text-field')
    await card.getByRole('radiogroup', { name: 'Field style' }).getByText(variant, { exact: false }).click()
    const input = card.getByRole('textbox', { name: 'Project name' })
    await card.locator('label').filter({ hasText: 'Project name' }).click()
    await expect(input).toBeFocused()
    await input.press('Tab')
    await expect(input).toHaveAttribute('aria-invalid', 'true')
    const edge = input.locator('..').locator('..')
    const bounds = await edge.boundingBox()
    await input.focus()
    await edge.hover()
    const errorColor = await card.getByText('Enter a name to continue.', { exact: true }).evaluate(element => getComputedStyle(element).color)
    await expect.poll(() => edge.evaluate(element => getComputedStyle(element).borderColor)).toBe(errorColor)
    expect((await edge.boundingBox())?.height).toBe(bounds?.height)
    expect((await edge.boundingBox())?.width).toBe(bounds?.width)
    expect(await edge.evaluate(element => getComputedStyle(element).boxShadow)).toContain('inset')
    await input.fill('A considered detail')
    await expect(input).not.toHaveAttribute('aria-invalid', 'true')
  })
}

test('changing a complete form style keeps edits, validation, and saving intact', async ({ page }) => {
  const card = await example(page, 'profile-form')
  const name = card.getByRole('textbox', { name: 'Full name' })
  await name.fill('Jamie Chen')
  for (const style of ['Outlined', 'Subtle', 'Plain']) {
    await card.getByRole('radiogroup', { name: 'Field style' }).getByText(style, { exact: true }).click()
    await expect(name).toHaveValue('Jamie Chen')
  }
  await card.getByRole('button', { name: 'Save profile' }).click()
  await expect(card.getByRole('status')).toHaveText('Profile saved. Your details are up to date.')
  await name.fill('')
  await card.getByRole('button', { name: 'Save profile' }).click()
  await expect(name).toBeFocused()
  await expect(name).toHaveAttribute('aria-invalid', 'true')
})

for (const brand of ['bbb', 'studio']) for (const mode of ['light', 'dark']) {
  test(`field variants and search reflow and pass accessibility checks in ${brand} ${mode}`, async ({ page }) => {
    test.setTimeout(120000)
    await page.addInitScript(({ brand, mode }) => localStorage.setItem('bbb-gallery-appearance', JSON.stringify({ brand, mode, density: 'comfortable' })), { brand, mode })
    const card = await example(page, 'field-variants')
    await page.evaluate(() => { document.documentElement.style.fontSize = '200%' })
    for (const style of ['Filled', 'Outlined', 'Subtle', 'Plain']) {
      await card.getByRole('radiogroup', { name: 'Field style' }).getByText(style, { exact: true }).click()
      for (const width of [1440, 390, 320]) {
        await page.setViewportSize({ width, height: 1000 })
        expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${style} page at ${width}`).toBe(true)
        expect(await card.locator('.gallery-card__preview').evaluate(element => element.scrollWidth <= element.clientWidth), `${style} preview at ${width}`).toBe(true)
      }
      expect((await new AxeBuilder({ page }).include('.gallery-card').withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations).toEqual([])
    }
    const searchCard = await example(page, 'search-field')
    await page.evaluate(() => { document.documentElement.style.fontSize = '200%' })
    await searchCard.getByRole('searchbox', { name: 'Find a document' }).fill('review')
    for (const width of [1440, 390, 320]) {
      await page.setViewportSize({ width, height: 1000 })
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `search page at ${width}`).toBe(true)
      expect(await searchCard.locator('.gallery-card__preview').evaluate(element => element.scrollWidth <= element.clientWidth), `search preview at ${width}`).toBe(true)
    }
    expect((await new AxeBuilder({ page }).include('.gallery-card').withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations).toEqual([])
  })
}

