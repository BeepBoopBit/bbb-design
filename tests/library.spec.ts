import { expect, test } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import { readFileSync } from 'node:fs'

const release = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8')).version
const fixture = '/tests/fixtures/library.html'

test('hover cards support focus, interactive content, Escape, controlled state, and disabled previews', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  await page.goto(fixture)
  const trigger = page.getByRole('link', { name: 'Project link', exact: true })
  await trigger.focus()
  const card = page.locator('.bbb-hover-card').filter({ hasText: 'Project preview' })
  await expect(card).toBeVisible()
  await trigger.press('Tab')
  await expect(card.getByRole('link', { name: 'Open project' })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(card.getByRole('button', { name: 'Preview action' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(card).toBeHidden()
  await expect(trigger).toBeFocused()
  await trigger.press('Enter')
  await expect(page).toHaveURL(/#destination$/)
  const controlled = page.getByRole('button', { name: 'Controlled trigger', exact: true })
  await controlled.focus()
  await expect(page.getByText('Controlled content', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Close preview', exact: true }).click()
  await expect(page.getByText('Controlled content', { exact: true })).toBeHidden()
  await page.getByRole('link', { name: 'Disabled preview link', exact: true }).focus()
  await expect(page.getByText('Hidden preview', { exact: true })).toBeHidden()
  await page.keyboard.press('Enter')
  await expect(page).toHaveURL(/#destination$/)
  expect(errors).toEqual([])
})

test('hover cards remain available when the pointer moves into their content', async ({ page }) => {
  await page.goto(fixture)
  await page.mouse.move(2, 2)
  const trigger = page.getByRole('link', { name: 'Project link', exact: true })
  await trigger.hover()
  const card = page.locator('.bbb-hover-card').filter({ hasText: 'Project preview' })
  await expect(card).toBeVisible()
  await card.getByRole('link', { name: 'Open project' }).hover()
  await page.waitForTimeout(250)
  await expect(card).toBeVisible()
  await page.getByRole('heading', { level: 1 }).hover()
  await expect(card).toBeHidden()
})

test('touch long press opens a hover preview without following its link', async ({ page, browserName }) => {
  test.skip(browserName !== 'chromium', 'CDP supplies real touch input for this check.')
  await page.goto(fixture)
  const session = await page.context().newCDPSession(page)
  await session.send('Emulation.setTouchEmulationEnabled', { enabled: true })
  const target = page.getByRole('link', { name: 'Project link', exact: true })
  const box = (await target.boundingBox())!
  await session.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: box.x + 15, y: box.y + box.height / 2 }] })
  await expect(page.getByRole('heading', { name: 'Project preview', exact: true })).toBeVisible()
  await session.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  await expect(page).not.toHaveURL(/#destination$/)
  const link = (await page.getByRole('link', { name: 'Open project', exact: true }).boundingBox())!
  await session.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: link.x + 15, y: link.y + link.height / 2 }] })
  await session.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  await expect(page).toHaveURL(/#destination$/)
})

for (const locale of ['en-US', 'ar']) test(`navigation disclosures preserve native links and keyboard order in ${locale}`, async ({ page }) => {
  await page.goto(`${fixture}?locale=${locale}`)
  const nav = page.getByRole('navigation', { name: 'Fixture navigation' })
  const trigger = nav.getByRole('button', { name: 'Learn', exact: true })
  await expect(nav.getByRole('link', { name: 'Overview' })).toHaveAttribute('aria-current', 'page')
  await expect(nav.getByRole('menu')).toHaveCount(0)
  await trigger.press('ArrowDown')
  const first = nav.getByRole('link', { name: 'Quick start', exact: false })
  await expect(first).toBeFocused()
  await expect(trigger).toHaveAttribute('aria-expanded', 'true')
  await page.keyboard.press('Tab')
  await expect(nav.getByRole('link', { name: 'Core concepts' })).toBeFocused()
  await expect(nav.getByRole('link', { name: 'Core concepts' })).toHaveAttribute('rel', 'noopener noreferrer')
  await page.keyboard.press('Escape')
  await expect(trigger).toBeFocused()
  await expect(first).toBeHidden()
  await trigger.press('Space')
  await trigger.press('Tab')
  await expect(first).toBeFocused()
  await nav.getByRole('button', { name: 'More', exact: true }).click()
  await expect(first).toBeHidden()
  await expect(nav.getByRole('link', { name: 'Browse examples' })).toBeVisible()
  await page.getByRole('button', { name: 'After navigation', exact: true }).focus()
  await expect(nav.getByRole('link', { name: 'Browse examples' })).toBeHidden()
  await trigger.click()
  await page.getByRole('heading', { level: 1 }).click()
  await expect(first).toBeHidden()
  await trigger.click()
  await first.click()
  await expect(page).toHaveURL(/#destination$/)
  await expect(first).toBeHidden()
  await expect(nav.getByRole('button', { name: 'Soon', exact: true })).toBeDisabled()
})

for (const variant of ['filled', 'outlined', 'subtle', 'plain']) test(`${variant} native selects retain validation, multiple selection, refs, and form reset`, async ({ page }) => {
  await page.goto(`${fixture}?variant=${variant}`)
  const region = page.getByRole('combobox', { name: 'Region', exact: true })
  await expect(region).toHaveAccessibleDescription('Choose a nearby region.')
  await region.selectOption('singapore')
  await page.getByRole('combobox', { name: 'Controlled choice' }).selectOption('two')
  await page.getByRole('listbox', { name: 'Days', exact: true }).selectOption(['Tuesday', 'Wednesday'])
  await page.getByRole('button', { name: 'Submit fields' }).click()
  const required = page.getByRole('combobox', { name: 'Required choice' })
  await expect(required).toBeFocused()
  await expect(required).toHaveAccessibleDescription('Make a selection.')
  await expect(page.getByLabel('Submitted fields')).toBeEmpty()
  await required.selectOption('yes')
  await page.getByRole('button', { name: 'Submit fields' }).click()
  await expect(page.getByLabel('Submitted fields')).toHaveText('[["region","singapore"],["choice","two"],["days","Tuesday"],["days","Wednesday"]]')
  await page.getByRole('button', { name: 'Reset fields' }).click()
  await expect(region).toHaveValue('manila')
  await expect(page.getByRole('listbox', { name: 'Days', exact: true })).toHaveValues(['Monday'])
  await page.getByRole('button', { name: 'Focus region' }).click()
  await expect(region).toBeFocused()
  await page.getByRole('heading', { level: 1 }).click()
  const surface = region.locator('xpath=../..')
  await surface.click({ position: { x: 3, y: (await surface.boundingBox())!.height / 2 } })
  await expect(region).toBeFocused()
  await expect(page.getByRole('combobox', { name: 'Disabled choice' })).toBeDisabled()
})

