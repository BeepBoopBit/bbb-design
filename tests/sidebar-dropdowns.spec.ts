import { expect, test } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

for (const mode of ['light', 'dark']) {
  test(`sidebar dropdowns support keyboard navigation, rail mode, and mobile sheets in ${mode}`, async ({ page }) => {
    await page.addInitScript(mode => {
      localStorage.setItem('bbb-gallery-appearance', JSON.stringify({ brand: 'bbb', mode, density: 'comfortable' }))
    }, mode)
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.goto('/gallery')
    const search = page.getByRole('searchbox', { name: 'Search gallery' })
    await search.fill('Sidebar dropdowns')
    await page.getByRole('radio', { name: 'Pages', exact: true }).focus()
    await page.keyboard.press('ArrowRight')
    await expect(page.getByRole('radio', { name: 'Sections', exact: true })).toBeChecked()
    const pattern = page.getByRole('group', { name: 'Sidebar dropdowns example', exact: true })
    const nav = pattern.getByRole('navigation', { name: 'Studio desktop navigation' })
    const workspace = nav.getByRole('button', { name: 'Workspace', exact: true })
    await workspace.focus()
    await page.keyboard.press('Enter')
    await expect(workspace).toHaveAttribute('aria-expanded', 'false')
    await expect(nav.getByRole('link', { name: 'Projects' })).toBeHidden()
    await page.keyboard.press('Space')
    await page.keyboard.press('Tab')
    await expect(nav.getByRole('link', { name: 'Overview' })).toBeFocused()
    await nav.getByRole('link', { name: 'Projects' }).click()
    await expect(pattern.getByRole('heading', { name: 'Projects', exact: true })).toBeFocused()
    await pattern.getByRole('button', { name: 'Collapse sidebar' }).click()
    await expect(workspace).toHaveAttribute('aria-expanded', 'true')
    await nav.getByRole('button', { name: 'Manage', exact: true }).click()
    await nav.getByRole('link', { name: /Members/ }).click()
    await expect(pattern.getByRole('heading', { name: 'Members', exact: true })).toBeFocused()
    await expect(nav.getByRole('link', { name: /Members/ })).toHaveAttribute('aria-current', 'page')
    await pattern.getByRole('button', { name: 'Expand sidebar' }).click()
    await expect(nav.getByRole('button', { name: 'Manage', exact: true })).toHaveAttribute('aria-expanded', 'true')
    expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations).toEqual([])
    await page.setViewportSize({ width: 390, height: 844 })
    const trigger = pattern.getByRole('button', { name: 'Open workspace navigation' })
    await trigger.click()
    const sheet = page.getByRole('dialog', { name: 'Workspace navigation', exact: true })
    await sheet.getByRole('button', { name: 'Manage', exact: true }).click()
    await sheet.getByRole('link', { name: /Members/ }).click()
    await expect(sheet).toBeHidden()
    await expect(pattern.getByRole('heading', { name: 'Members', exact: true })).toBeFocused()
    await trigger.click()
    await page.keyboard.press('Escape')
    await expect(trigger).toBeFocused()
    await trigger.click()
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.keyboard.press('Escape')
    await expect(pattern.getByRole('heading', { name: 'Members', exact: true })).toBeFocused()
  })

}

for (const width of [320, 390]) {
  test(`sidebar dropdowns fit at ${width}px with enlarged text`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 })
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.goto('/gallery')
    await page.getByRole('searchbox', { name: 'Search gallery' }).fill('Sidebar dropdowns')
    await page.evaluate(() => { document.documentElement.style.fontSize = '200%' })
    const pattern = page.getByRole('group', { name: 'Sidebar dropdowns example', exact: true })
    expect(await pattern.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
    await pattern.getByRole('button', { name: 'Open workspace navigation' }).click()
    const sheet = page.getByRole('dialog', { name: 'Workspace navigation', exact: true })
    await sheet.getByRole('button', { name: 'Projects', exact: true }).click()
    await sheet.getByRole('button', { name: 'Projects', exact: true }).click()
    expect(await sheet.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
    await expect(sheet.getByRole('link', { name: /Members/ })).toBeVisible()
  })
}

for (const mode of ['light', 'dark']) {
  test(`page dropdowns keep section labels and navigate nested destinations in ${mode}`, async ({ page }) => {
    await page.addInitScript(mode => {
      localStorage.setItem('bbb-gallery-appearance', JSON.stringify({ brand: 'bbb', mode, density: 'comfortable' }))
    }, mode)
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.goto('/gallery')
    await page.getByRole('searchbox', { name: 'Search gallery' }).fill('Sidebar dropdowns')
    const pattern = page.getByRole('group', { name: 'Sidebar dropdowns example', exact: true })
    const nav = pattern.getByRole('navigation', { name: 'Studio desktop navigation' })
    await expect(nav.getByRole('button', { name: 'Workspace', exact: true })).toHaveCount(0)
    await expect(nav.getByText('Workspace', { exact: true })).toBeVisible()
    const projects = nav.getByRole('button', { name: 'Projects', exact: true })
    await projects.focus()
    await page.keyboard.press('Enter')
    await expect(projects).toHaveAttribute('aria-expanded', 'false')
    await expect(nav.getByRole('link', { name: 'All projects' })).toBeHidden()
    await page.keyboard.press('Space')
    await page.keyboard.press('Tab')
    await expect(nav.getByRole('link', { name: 'All projects' })).toBeFocused()
    await nav.getByRole('link', { name: 'Active projects', exact: true }).click()
    await expect(pattern.getByRole('heading', { name: 'Active projects', exact: true })).toBeFocused()
    await expect(pattern.getByText('Customer stories', { exact: true })).toHaveCount(0)
    await expect(nav.getByRole('link', { name: 'Active projects' })).toHaveAttribute('aria-current', 'page')
    await projects.click()
    await expect(projects).toHaveAttribute('data-current', 'true')
    await pattern.getByRole('button', { name: 'Collapse sidebar' }).click()
    await expect(projects).toHaveAttribute('aria-expanded', 'false')
    await projects.focus()
    await page.keyboard.press('Enter')
    await nav.getByRole('link', { name: 'In review', exact: true }).click()
    await expect(pattern.getByRole('heading', { name: 'In review', exact: true })).toBeFocused()
    await expect(pattern.getByText('Customer stories', { exact: true })).toBeVisible()
    await pattern.getByRole('button', { name: 'Expand sidebar' }).click()
    expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations).toEqual([])
    await page.setViewportSize({ width: 390, height: 844 })
    await pattern.getByRole('button', { name: 'Open workspace navigation' }).click()
    const sheet = page.getByRole('dialog', { name: 'Workspace navigation', exact: true })
    const mobileProjects = sheet.getByRole('button', { name: 'Projects', exact: true })
    await mobileProjects.focus()
    await page.keyboard.press('Space')
    await expect(mobileProjects).toHaveAttribute('aria-expanded', 'false')
    await page.keyboard.press('Enter')
    await sheet.getByRole('link', { name: 'All projects', exact: true }).click()
    await expect(sheet).toBeHidden()
    await expect(pattern.getByRole('heading', { name: 'Projects', exact: true })).toBeFocused()
  })
}
