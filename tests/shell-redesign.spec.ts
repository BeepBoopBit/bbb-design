import { expect, test } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import { galleryCounts } from './galleryCounts'

test('Gallery destinations, legacy links, help downloads, and header focus work', async ({ page }) => {
  await page.goto('/gallery?category=products&product=notes-product&item=notes-product')
  const navigation = page.getByRole('navigation', { name: 'Main navigation', exact: true })
  await expect(page.getByRole('article')).toHaveCount(galleryCounts.all)
  await expect(navigation.getByRole('link', { name: 'Gallery', exact: true })).toHaveAttribute('aria-current', 'page')
  await navigation.getByRole('link', { name: `Patterns ${galleryCounts.patterns}` }).click()
  await expect(page.getByRole('article')).toHaveCount(galleryCounts.patterns)
  await expect(page).toHaveURL(/\/gallery\?category=patterns$/)
  await expect(page.getByRole('main')).toBeFocused()
  await page.goBack()
  await expect(page.getByRole('article')).toHaveCount(galleryCounts.all)
  const help = page.locator('.gallery-sidebar').getByRole('button', { name: 'Help & resources' })
  await help.click()
  const download = page.waitForEvent('download')
  await page.getByRole('link', { name: 'Component documentation' }).click()
  expect((await download).suggestedFilename()).toBe('BBB-components.md')
  await page.keyboard.press('Escape')
  await expect(help).toBeFocused()
})

test('workspace account switches context, edits settings, and restores a demo session', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('searchbox', { name: 'Search gallery' }).fill('Workspace shell')
  const shell = page.getByRole('group', { name: 'Workspace shell example', exact: true })
  const account = shell.getByRole('button', { name: 'Studio, account and workspaces', exact: true })
  await account.focus()
  await page.keyboard.press('Enter')
  await page.getByRole('button', { name: 'Personal', exact: true }).click()
  const personal = shell.getByRole('button', { name: 'Personal, account and workspaces', exact: true })
  await expect(personal).toBeFocused()
  await expect(shell).toContainText('A space for your own ideas.')
  await personal.click()
  await page.getByRole('button', { name: 'Account settings', exact: true }).click()
  await page.getByRole('textbox', { name: 'Display name', exact: true }).fill('Jordan Lee')
  await page.keyboard.press('Escape')
  await personal.click()
  await expect(page.getByRole('dialog', { name: 'Jordan Lee', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Log out', exact: true }).click()
  await expect(shell).toContainText('Sign in through the account menu')
  const signedOut = shell.getByRole('button', { name: 'Account, signed out', exact: true })
  await expect(signedOut).toBeFocused()
  await signedOut.click()
  await page.getByRole('button', { name: 'Sign in to preview', exact: true }).click()
  await expect(personal).toBeFocused()
})

for (const mode of ['light', 'dark']) test(`shell reflows at narrow widths with enlarged text in ${mode}`, async ({ page }) => {
  await page.goto('/')
  await page.evaluate(mode => localStorage.setItem('bbb-gallery-appearance', JSON.stringify({ brand: 'bbb', mode, density: 'comfortable' })), mode)
  await page.reload()
  await page.getByRole('searchbox', { name: 'Search gallery' }).fill('Workspace shell')
  await page.evaluate(() => { document.documentElement.style.fontSize = '200%' })
  for (const width of [320, 390]) {
    await page.setViewportSize({ width, height: 1000 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1)
    const account = page.getByRole('button', { name: 'Studio, account and workspaces', exact: true })
    await account.click()
    for (let step = 0; step < 6; step++) await page.keyboard.press('Tab')
    await expect(page.getByRole('button', { name: 'Log out', exact: true })).toBeFocused()
    await expect(page.getByRole('button', { name: 'Log out', exact: true })).toBeInViewport()
    expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations).toEqual([])
    await page.keyboard.press('Escape')
    await expect(account).toBeFocused()
    await page.getByRole('button', { name: 'Open gallery navigation', exact: true }).click()
    const sheet = page.getByRole('dialog', { name: 'Gallery navigation', exact: true })
    await sheet.getByRole('button', { name: 'Help & resources' }).click()
    await expect(page.getByRole('link', { name: 'Component documentation' })).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(page.locator('.bbb-popover')).toHaveCount(0)
    await expect(sheet.getByRole('button', { name: 'Help & resources' })).toBeFocused()
    await page.keyboard.press('Escape')
    await expect(sheet).not.toBeVisible()
  }
})

test('branded shell is the default and document layout preserves each workspace state', async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('.gallery-desktop-toggle .bbb-brand-logo')).toBeVisible()
  await page.getByRole('searchbox', { name: 'Search gallery' }).fill('Workspace shell')
  const shell = page.getByRole('group', { name: 'Workspace shell example', exact: true })
  await expect(shell.locator('.workspace-shell__desktop-toggle .bbb-brand-logo')).toBeVisible()
  await shell.getByRole('navigation', { name: 'Studio desktop navigation' }).getByRole('link', { name: 'Projects 3' }).click()
  const variants = page.getByRole('radiogroup', { name: 'Workspace layout', exact: true })
  await variants.getByRole('radio', { name: 'Branded', exact: true }).focus()
  await page.keyboard.press('ArrowRight')
  await expect(variants.getByRole('radio', { name: 'Document', exact: true })).toBeChecked()
  const document = page.getByRole('group', { name: 'Document workspace example', exact: true })
  await expect(document.locator('.bbb-brand-logo')).toHaveCount(0)
  await expect(document.getByRole('heading', { name: 'A thoughtful starting point', exact: true })).toBeVisible()
  await page.keyboard.press('ArrowLeft')
  await expect(variants.getByRole('radio', { name: 'Branded', exact: true })).toBeChecked()
  await expect(shell.locator('.workspace-shell__desktop-toggle .bbb-brand-logo')).toBeVisible()
  await expect(shell.getByRole('heading', { name: 'Projects', exact: true })).toBeVisible()
})
