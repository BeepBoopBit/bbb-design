for (const width of [1440, 390, 320]) {
  test(`select chevron stays centered when opened at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 1000 })
    if (width < 400) {
      await page.addStyleTag({ content: 'html { font-size: 200%; }' })
    }
    const card = await example(page, 'Customization')
    const trigger = card.getByRole('button', { name: /Custom option content/ })
    const surface = card.locator('.bbb-select .bbb-field__surface')
    const icon = trigger.locator('.bbb-icon')
    const centerOffset = async () => {
      const fieldBox = await surface.boundingBox()
      const iconBox = await icon.boundingBox()
      return Math.abs((iconBox!.y + iconBox!.height / 2) - (fieldBox!.y + fieldBox!.height / 2))
    }
    await expect.poll(centerOffset).toBeLessThan(1)
    await surface.scrollIntoViewIfNeeded()
    const chevronBox = await icon.boundingBox()
    await page.mouse.click(chevronBox!.x + chevronBox!.width / 2, chevronBox!.y + chevronBox!.height / 2)
    await expect(trigger).toHaveAttribute('aria-expanded', 'true')
    await expect(icon).toHaveCSS('rotate', '180deg')
    await expect.poll(centerOffset).toBeLessThan(1)
    await page.keyboard.press('Escape')
    await expect(trigger).toBeFocused()
    await expect(icon).toHaveCSS('rotate', 'none')
    await expect.poll(centerOffset).toBeLessThan(1)
    await trigger.press('ArrowDown')
    await page.getByRole('option', { name: /Jamie Chen/ }).click()
    await expect(trigger).toContainText('Jamie Chen')
    await expect(trigger).toBeFocused()
    await expect.poll(centerOffset).toBeLessThan(1)
  })
}
