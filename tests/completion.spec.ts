test('workspace search cancels stale results and focuses the selected detail', async ({ page }) => {
  const card = await example(page, 'Workspace search')
  const search = card.getByRole('searchbox', { name: 'Search workspace' })
  await page.setViewportSize({ width: 390, height: 1000 })
  await search.focus()
  await page.keyboard.press('Tab')
  const results = card.getByRole('region', { name: 'Search results', exact: true })
  await expect(results).toBeFocused()
  if (await results.evaluate(element => element.scrollHeight > element.clientHeight)) {
    await page.keyboard.press('End')
    await expect.poll(() => results.evaluate(element => element.scrollTop)).toBeGreaterThan(0)
  }
  await page.setViewportSize({ width: 1440, height: 1000 })
  await search.fill('brand')
  await search.fill('notes')
  await expect(card.getByRole('menuitem', { name: /Design review notes/ })).toBeVisible()
  await expect(card.getByRole('menuitem')).toHaveCount(1)
  await page.keyboard.press('Enter')
  await expect(card.getByRole('heading', { name: 'Design review notes' })).toBeFocused()
  await choose(page, 'Search scope', 'People')
  await expect(card.getByText('No results found')).toBeVisible()
  await card.getByRole('button', { name: 'Clear search' }).click()
  await expect(card.getByRole('menuitem', { name: /Alex Morgan/ })).toBeVisible()
})

test('advanced table supports visibility, pointer and keyboard resizing, details, and editing', async ({ page }) => {
  const card = await example(page, 'Advanced table')
  const resizer = card.getByRole('separator', { name: 'Resize Project column' })
  await resizer.focus()
  const initial = Number(await resizer.getAttribute('aria-valuenow'))
  await page.keyboard.press('ArrowRight')
  await expect.poll(async () => Number(await resizer.getAttribute('aria-valuenow'))).toBeGreaterThan(initial)
  const box = (await resizer.boundingBox())!
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width / 2 + 40, box.y + box.height / 2)
  await page.mouse.up()
  await expect.poll(async () => Number(await resizer.getAttribute('aria-valuenow'))).toBeGreaterThan(initial + 30)
  await card.getByRole('button', { name: 'Columns', exact: true }).click()
  await page.getByRole('checkbox', { name: 'Owner', exact: true }).focus()
  await page.keyboard.press('Space')
  await page.keyboard.press('Escape')
  await expect(card.getByRole('separator', { name: 'Resize Owner column' })).toBeHidden()
  await card.getByRole('button', { name: 'Expand Brand refresh' }).click()
  await expect(card.getByText('Identity, guidelines, and a thoughtful rollout.')).toBeVisible()
  const edit = card.getByRole('button', { name: 'Edit Brand refresh project name' })
  await edit.click()
  let input = card.getByRole('textbox', { name: 'Brand refresh project name', exact: true })
  await input.fill('Discard this')
  await page.keyboard.press('Escape')
  await expect(edit).toBeFocused()
  await edit.click()
  input = card.getByRole('textbox', { name: 'Brand refresh project name', exact: true })
  await input.fill('')
  await page.keyboard.press('Enter')
  await expect(input).toHaveAttribute('aria-invalid', 'true')
  await input.fill('Refined identity')
  await page.keyboard.press('Enter')
  await expect(card.getByRole('button', { name: 'Edit Refined identity project name' })).toBeFocused()
  await card.getByRole('button', { name: 'Reset columns' }).click()
  await expect(card.getByRole('separator', { name: 'Resize Owner column' })).toBeVisible()
  await card.getByRole('button', { name: 'Columns', exact: true }).click()
  for (const name of ['Owner', 'Status']) {
    await page.getByRole('checkbox', { name, exact: true }).focus()
    await page.keyboard.press('Space')
  }
  await page.keyboard.press('Escape')
  await resizer.focus()
  for (const [key, bound] of [['Home', 'aria-valuemin'], ['End', 'aria-valuemax']]) {
    await page.keyboard.press(key)
    const expected = Number(await resizer.getAttribute(bound))
    await expect(resizer).toHaveAttribute('aria-valuenow', String(expected))
    await expect.poll(() => resizer.evaluate(element => element.closest('th')!.getBoundingClientRect().width))
      .toBeCloseTo(expected, 0)
  }
})

