import { expect, test, type Page } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

async function example(page: Page, name: string) {
  await page.getByRole('searchbox', { name: 'Search gallery' }).fill(name)
  return page.getByRole('article', { name, exact: true })
}
async function choose(page: Page, label: string, option: string) {
  await page.getByRole('button', { name: new RegExp(label) }).click()
  await page.getByRole('option', { name: option, exact: true }).click()
}
test.beforeEach(async ({ page }) => { await page.goto('/gallery') })

test('toast actions support keyboard Undo and fit enlarged narrow layouts', async ({ page }) => {
  const card = await example(page, 'Toast')
  const trigger = card.getByRole('button', { name: 'Try Undo notification', exact: true })
  for (const width of [1440, 390, 320]) {
    await page.setViewportSize({ width, height: 1000 })
    await page.evaluate(enlarged => {
      document.documentElement.style.fontSize = enlarged ? '200%' : ''
    }, width < 400)
    await trigger.click()
    const notifications = page.getByRole('region', { name: 'Notifications', exact: true })
    await expect(notifications.getByText('Item archived', { exact: true })).toBeVisible()
    expect(await notifications.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
    const bounds = await notifications.boundingBox()
    expect(bounds!.x).toBeGreaterThanOrEqual(0)
    expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(width)
    await page.keyboard.press('F6')
    await expect.poll(() => notifications.evaluate(el => el.contains(document.activeElement))).toBe(true)
    await notifications.getByRole('button', { name: 'Undo', exact: true }).press('Enter')
    await expect(notifications).toHaveCount(0)
    await expect(card.getByRole('status')).toHaveText('Item restored.')
    await expect(trigger).toBeFocused()
  }
})

test('password reveal preserves the value, caret, focus, and disabled state', async ({ page }) => {
  const card = await example(page, 'Password field')
  const input = card.getByLabel('Workspace password', { exact: true })
  await input.fill('A longer secret')
  await input.evaluate((element: HTMLInputElement) => element.setSelectionRange(2, 6))
  await card.getByRole('button', { name: 'Show password' }).click()
  await expect(input).toHaveAttribute('type', 'text')
  await expect(input).toBeFocused()
  expect(await input.evaluate((element: HTMLInputElement) => [element.selectionStart, element.selectionEnd])).toEqual([2, 6])
  await card.getByRole('button', { name: 'Hide password' }).click()
  await expect(input).toHaveAttribute('type', 'password')
  await expect(input).toHaveValue('A longer secret')
  await choose(page, 'Password example state', 'Error')
  await expect(input).toHaveAttribute('aria-invalid', 'true')
  await choose(page, 'Password example state', 'Disabled')
  await expect(input).toBeDisabled()
  await expect(card.getByRole('button', { name: 'Show password' })).toBeDisabled()
})

test('verification codes retain leading zeros and accept pasted or localized digits', async ({ page }) => {
  const card = await example(page, 'Verification code')
  const input = card.getByRole('textbox', { name: 'Sign-in code', exact: true })
  await input.fill('12')
  await card.getByRole('button', { name: 'Verify sign-in code' }).click()
  await expect(input).toHaveAttribute('aria-invalid', 'true')
  await input.fill('٠١ ٢٣-٤٥')
  await expect(input).toHaveValue('012345')
  await input.fill('۰۱ ۲۳-۴۵')
  await expect(input).toHaveValue('012345')
  await expect(input).toHaveAttribute('autocomplete', 'one-time-code')
  await card.getByRole('button', { name: 'Verify sign-in code' }).click()
  await expect(card.getByRole('status')).toContainText('Code accepted')
  await input.fill('12345678')
  await expect(input).toHaveValue('123456')
  await choose(page, 'Verification code example state', 'Disabled')
  await expect(input).toBeDisabled()
})

