test('split actions retain normal Tab order and menu focus return', async ({ page }) => {
  await page.goto('/gallery?item=button-group')
  const group = page.getByRole('group', { name: 'Document actions' })
  await group.getByRole('button', { name: 'Save draft', exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('article').getByRole('status')).toContainText('Your draft is saved.')
  await page.keyboard.press('Tab')
  const trigger = group.getByRole('button', { name: 'More save options' })
  await expect(trigger).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await page.getByRole('menuitem', { name: 'Save a copy' }).click()
  await expect(page.getByRole('article').getByRole('status')).toContainText('A copy is saved.')
  await expect(trigger).toBeFocused()
  await expect(page.getByRole('button', { name: 'Redo', exact: true })).toBeDisabled()
})

test('toggles support multiple selection, keyboard navigation, and disabled choices', async ({ page }) => {
  await page.goto('/gallery?item=toggle-group')
  const bold = page.getByRole('button', { name: 'Bold', exact: true })
  const italic = page.getByRole('button', { name: 'Italic', exact: true })
  await expect(bold).toHaveAttribute('aria-pressed', 'true')
  await bold.focus()
  await bold.press('ArrowRight')
  await expect(italic).toBeFocused()
  await italic.press('Space')
  await expect(italic).toHaveAttribute('aria-pressed', 'true')
  await expect(bold).toHaveAttribute('aria-pressed', 'true')
  await italic.press('ArrowRight')
  const underline = page.getByRole('button', { name: 'Underline', exact: true })
  await expect(underline).toBeFocused()
  await underline.press('ArrowRight')
  await expect(underline).toBeFocused()
  await underline.press('ArrowLeft')
  await italic.press('ArrowLeft')
  await expect(bold).toBeFocused()
  await bold.press('Enter')
  await expect(bold).toHaveAttribute('aria-pressed', 'false')
  await expect(page.getByRole('button', { name: 'Strike', exact: true })).toBeDisabled()
})

for (const locale of ['en-US', 'ar']) {
  test(`controlled, required, vertical, and disabled selection in ${locale}`, async ({ page }) => {
    await page.goto(`/tests/fixtures/compositions.html?locale=${locale}`)
    const toggle = page.getByRole('button', { name: 'Controlled toggle', exact: true })
    await toggle.press('Space')
    await expect(toggle).toHaveAttribute('aria-pressed', 'true')
    const single = page.getByRole('radiogroup', { name: 'Required selection' })
    const one = single.getByRole('radio', { name: 'One', exact: true })
    const two = single.getByRole('radio', { name: 'Two', exact: true })
    await one.click()
    await expect(one).toBeChecked()
    await one.press(locale === 'ar' ? 'ArrowLeft' : 'ArrowRight')
    await expect(two).toBeFocused()
    await two.press('Enter')
    await expect(two).toBeChecked()
    await expect(one).not.toBeChecked()
    const vertical = page.getByRole('toolbar', { name: 'Vertical choices' })
    await vertical.getByRole('button', { name: 'Top', exact: true }).press('ArrowDown')
    await expect(vertical.getByRole('button', { name: 'Bottom', exact: true })).toBeFocused()
    for (const name of ['Disabled A', 'Disabled B', 'Disabled toggle']) await expect(page.getByRole('button', { name, exact: true })).toBeDisabled()
    await page.getByRole('button', { name: 'Reset controlled state' }).click()
    await expect(toggle).toHaveAttribute('aria-pressed', 'false')
    await expect(one).toBeChecked()
  })
}

for (const variant of ['filled', 'outlined', 'subtle', 'plain']) {
  test(`${variant} input groups preserve names, native forms, refs, addon focus, and validation`, async ({ page }) => {
    await page.goto(`/tests/fixtures/compositions.html?variant=${variant}`)
    const website = page.getByRole('textbox', { name: 'Website', exact: true })
    await expect(website).toHaveAccessibleDescription('Enter a subdomain.')
    await website.fill('hello')
    const currency = page.getByRole('combobox', { name: 'Currency' })
    await currency.focus()
    await currency.selectOption('EUR')
    await expect(currency).toBeFocused()
    await page.getByRole('textbox', { name: 'Notes', exact: true }).fill('A new note')
    await page.getByRole('button', { name: 'Submit fields' }).click()
    await expect(page.getByLabel('Submitted fields')).toHaveText('{"website":"hello","currency":"EUR","budget":"24","notes":"A new note"}')
    await page.getByRole('button', { name: 'Focus website' }).click()
    await expect(website).toBeFocused()
    await page.getByRole('button', { name: 'Focus notes' }).click()
    await expect(page.getByRole('textbox', { name: 'Notes', exact: true })).toBeFocused()
    await expect(page.getByRole('textbox', { name: 'Read-only' })).toHaveAttribute('readonly', '')
    await expect(page.getByRole('textbox', { name: 'Disabled input' })).toBeDisabled()
    await expect(page.getByRole('textbox', { name: 'Invalid input' })).toHaveAttribute('aria-invalid', 'true')
    await expect(page.getByRole('textbox', { name: 'Invalid input' })).toHaveAccessibleDescription('Choose another value.')
    await page.getByRole('button', { name: 'Reset fields' }).click()
    await expect(website).toHaveValue('studio')
    await expect(currency).toHaveValue('USD')
    await expect(page.getByRole('textbox', { name: 'Notes', exact: true })).toHaveValue('Hello')
  })
}

test('collapsible supports a custom trigger, external state, hidden focus targets, and preserved values', async ({ page }) => {
  await page.goto('/tests/fixtures/compositions.html')
  const trigger = page.getByRole('button', { name: 'Custom options' })
  const field = page.getByRole('textbox', { name: 'Remembered value' })
  await expect(trigger).toHaveAttribute('aria-expanded', 'false')
  await expect(field).toBeHidden()
  await trigger.press('Enter')
  await expect(trigger).toHaveAttribute('aria-expanded', 'true')
  await expect(trigger).toHaveAttribute('aria-controls', /.+/)
  await trigger.press('Tab')
  await expect(field).toBeFocused()
  await field.fill('Keep this value')
  await trigger.press('Space')
  await expect(field).toBeHidden()
  await trigger.press('Space')
  await expect(field).toHaveValue('Keep this value')
  await page.getByRole('button', { name: 'Reset controlled state' }).click()
  await expect(trigger).toHaveAttribute('aria-expanded', 'false')
  await expect(page.getByRole('button', { name: 'Disabled options' })).toBeDisabled()
})

test('drawer anchors to the bottom, contains focus, scrolls its body, and restores focus through nested overlays', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 700 })
  await page.goto('/tests/fixtures/compositions.html?mode=dark&brand=studio&locale=ar&density=compact')
  const trigger = page.getByRole('button', { name: 'Open controlled drawer' })
  await trigger.click()
  const dialog = page.getByRole('dialog', { name: 'Drawer settings' })
  await expect(page.getByRole('textbox', { name: 'Drawer name' })).toBeFocused()
  const modal = page.locator('.bbb-modal-overlay--bottom .bbb-modal')
  await expect.poll(async () => Math.round((await modal.boundingBox())!.y + (await modal.boundingBox())!.height)).toBe(700)
  await expect(page.locator('.bbb-modal-overlay--bottom')).toHaveAttribute('data-bbb-brand', 'studio')
  await expect(page.locator('.bbb-modal-overlay--bottom')).toHaveAttribute('data-bbb-mode', 'dark')
  const body = dialog.locator('.bbb-dialog__body')
  expect(await body.evaluate(el => el.scrollHeight > el.clientHeight)).toBe(true)
  const footer = dialog.getByRole('button', { name: 'Finish drawer' })
  await footer.focus()
  await footer.press('Tab')
  expect(await dialog.evaluate(el => el.contains(document.activeElement))).toBe(true)
  const nestedTrigger = dialog.getByRole('button', { name: 'Open nested dialog' })
  await nestedTrigger.click()
  await expect(page.getByRole('dialog', { name: 'Nested dialog' })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog', { name: 'Nested dialog' })).toBeHidden()
  await expect(nestedTrigger).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(dialog).toBeHidden()
  await expect(trigger).toBeFocused()
  await trigger.click()
  await footer.click()
  await expect(dialog).toBeHidden()
  await expect(trigger).toBeFocused()
  await trigger.click()
  await page.mouse.click(3, 3)
  await expect(dialog).toBeHidden()
  await expect(trigger).toBeFocused()
})

